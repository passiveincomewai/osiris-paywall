import type { Metadata } from "next";
import Link from "next/link";
import { headers } from "next/headers";
import { notFound } from "next/navigation";
import { MapPin } from "lucide-react";
import SiteFooter from "@/components/SiteFooter";
import PublicCameraPlayer from "@/components/embed/PublicCameraPlayer";
import { db } from "@/lib/db";
import { publicEmbedCameras } from "@/lib/embed/public";
import { resolvePreviewCameras } from "@/lib/white-label-demo";
import ShareLinkButton from "./ShareLinkButton";
import WhiteLabelPreviewRequestForm from "./WhiteLabelPreviewRequestForm";

// ── White Label illustrative preview (share link) ───────────────────────
// A concept mock a prospect generated for themselves on
// /white-label/demo: their name + logo over real, current cameras near
// their chosen location. The labelling rules are absolute: the
// ILLUSTRATIVE PREVIEW banner is sticky (always on screen), the page
// states plainly that the organisation is not a customer and that this
// implies no partnership or endorsement, and the route is noindex with
// an unguessable slug. Cameras are re-validated against the rights
// registry's eligible set at render — a camera that loses clearance
// drops out, so a shared preview can shrink but never leak.

export const runtime = "nodejs";
export const dynamic = "force-dynamic";
/* A cold instance may first have to build the camera catalogue in-process. */
export const maxDuration = 60;

async function loadPreview(slug: string) {
  return db.whiteLabelPreview.findUnique({ where: { slug } }).catch(() => null);
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const row = await loadPreview(slug);
  return {
    title: row
      ? `Illustrative preview for ${row.orgName} — WorldEye White Label`
      : "Illustrative preview — WorldEye White Label",
    description:
      "A visitor-generated concept preview of the WorldEye White Label pilot: real cameras near a chosen location under a prospect's own name and logo. Not a live product.",
    robots: { index: false, follow: false },
  };
}

export default async function WhiteLabelPreviewPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const row = await loadPreview(slug);
  if (!row) notFound();

  const h = await headers();
  const host = h.get("x-forwarded-host") ?? h.get("host") ?? "worldeye.app";
  const proto = h.get("x-forwarded-proto") ?? "https";
  const eligible = await publicEmbedCameras(`${proto}://${host}`);
  const cameras = eligible ? resolvePreviewCameras(eligible, row.cameraIds) : null;

  return (
    <div className="docs-root min-h-screen bg-[#050508] text-zinc-100 relative overflow-x-clip">
      {/* Persistent illustrative labelling — sticky, always on screen. */}
      <div className="sticky top-0 z-50 bg-[#D4AF37] text-black">
        <p className="max-w-6xl mx-auto px-4 py-2 text-center text-[11px] sm:text-xs font-bold tracking-wide">
          ILLUSTRATIVE PREVIEW — a concept mock of the WorldEye White Label pilot,
          generated by the visitor. Not a live product; {row.orgName} is not a
          WorldEye customer, and this implies no partnership or endorsement.
        </p>
      </div>

      <div className="relative max-w-6xl mx-auto px-4 sm:px-6 pt-5">
        <div className="flex items-center justify-between gap-3">
          <Link href="/white-label/demo" className="text-sm text-white/45 hover:text-white transition">
            ← Build your own preview
          </Link>
          <ShareLinkButton />
        </div>

        {/* The prospect's branded header — the point of the preview. */}
        <header className="mt-5 rounded-3xl bg-white text-zinc-900 px-6 py-6 md:px-10 md:py-8 flex flex-col sm:flex-row sm:items-center gap-5 shadow-[0_18px_50px_rgba(0,0,0,0.45)]">
          {row.logoUrl ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={row.logoUrl}
              alt={`${row.orgName} logo`}
              className="h-14 md:h-16 max-w-[260px] object-contain self-start"
            />
          ) : (
            <span className="text-3xl md:text-4xl font-black tracking-tight self-start">
              {row.orgName}
            </span>
          )}
          <div className="sm:ml-auto sm:text-right">
            <p className="text-lg font-bold leading-tight">{row.orgName} — Live Cameras</p>
            <p className="text-sm text-zinc-500 mt-1 inline-flex items-center gap-1.5 sm:justify-end">
              <MapPin className="w-4 h-4" />
              {row.locationLabel}
              {row.locationDetail ? ` · ${row.locationDetail}` : ""}
            </p>
          </div>
        </header>

        {/* Camera wall — real frames, real attribution, via the embed player. */}
        <section className="mt-8">
          {cameras === null ? (
            <div className="rounded-3xl border border-white/10 bg-white/[0.02] p-8 text-center">
              <p className="text-white/70 font-medium">Camera frames are unavailable right now.</p>
              <p className="text-sm text-white/45 mt-2">
                The catalogue is momentarily unreachable — this preview&apos;s cameras
                will reappear when it is back. Nothing about the preview has changed.
              </p>
            </div>
          ) : cameras.length === 0 ? (
            <div className="rounded-3xl border border-white/10 bg-white/[0.02] p-8 text-center">
              <p className="text-white/70 font-medium">
                No cameras from this preview are currently cleared for redistribution.
              </p>
              <p className="text-sm text-white/45 mt-2">
                A White Label portal can only carry cameras whose source terms clear
                them for redistribution, and that set changes as terms are reviewed.
                Try the generator with a nearby location to see a full wall.
              </p>
            </div>
          ) : (
            <>
              <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-4">
                {cameras.map((cam) => (
                  <div key={cam.id} className="relative aspect-video rounded-2xl overflow-hidden border border-white/10">
                    <PublicCameraPlayer cam={cam} />
                  </div>
                ))}
              </div>
              {cameras.length < row.cameraIds.length && (
                <p className="text-xs text-white/40 mt-4">
                  Showing {cameras.length} of the {row.cameraIds.length} cameras this
                  preview was generated with — only cameras still cleared for
                  redistribution are shown.
                </p>
              )}
              <p className="text-xs text-white/40 mt-3">
                Real, current camera frames, carried through WorldEye&apos;s embed
                technology — the same players a pilot portal would use. Every frame
                keeps its operating agency&apos;s attribution.
              </p>
            </>
          )}
        </section>

        {/* Qualified demo request */}
        <section className="mt-16 max-w-3xl" id="request">
          <h2 className="text-2xl md:text-3xl font-bold tracking-tight">
            Request this for your organisation
          </h2>
          <p className="text-white/50 mt-3 leading-relaxed">
            Like what this could be? Tell us who you are and what you&apos;d
            show, and we&apos;ll scope the real pilot with you — collection,
            branding, your domain, and an honest quote from the indicative
            bands. White Label is an early-access pilot, configured by hand;
            there is no self-serve version yet, and this form doesn&apos;t
            create one.
          </p>
          <div className="mt-7">
            <WhiteLabelPreviewRequestForm
              orgName={row.orgName}
              locationLabel={row.locationLabel}
              previewPath={`/white-label/demo/${row.slug}`}
            />
          </div>
          <p className="text-sm text-white/40 mt-8">
            Prefer the full picture first?{" "}
            <Link href="/white-label" className="text-[#D4AF37] hover:underline">
              About the White Label pilot
            </Link>{" "}
            — what it includes, indicative pricing, and how onboarding works.
          </p>
        </section>
      </div>
      <SiteFooter />
    </div>
  );
}
